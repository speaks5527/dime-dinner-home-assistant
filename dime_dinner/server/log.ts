/**
 * Shared request/lifecycle logger.
 *
 * Lives apart from index.ts so modules can log without importing the file that
 * boots the server.
 */
export function log(message: string, source = "express"): void {
  const formattedTime = new Date().toLocaleTimeString("en-US", {
    hour: "numeric",
    minute: "2-digit",
    second: "2-digit",
    hour12: true,
  });

  console.log(`${formattedTime} [${source}] ${message}`);
}
